"""
Delivery channels for Tally Contact Engine (Slack, Email, Mock).

Enforces that no message can be transmitted without an authorization token
generated by an approved try_spend() transaction.
"""

from __future__ import annotations

import json
from typing import Any, Dict, List, Optional
import httpx

from tally.contact.composer import ComposedMessage


class ChannelDispatchError(Exception):
    pass


class BaseChannel:
    def send(self, message: ComposedMessage, auth_token: str) -> Dict[str, Any]:
        if not auth_token or not auth_token.startswith("AUTH-SPEND-"):
            raise ChannelDispatchError(f"Unauthorized dispatch attempt: missing valid spend token for {message.message_id}")
        return self._dispatch(message, auth_token)

    def _dispatch(self, message: ComposedMessage, auth_token: str) -> Dict[str, Any]:
        raise NotImplementedError


class MockChannel(BaseChannel):
    """In-memory testing channel that records all dispatched messages."""

    def __init__(self):
        self.dispatched: List[Dict[str, Any]] = []

    def _dispatch(self, message: ComposedMessage, auth_token: str) -> Dict[str, Any]:
        record = {
            "message_id": message.message_id,
            "recipient_id": message.recipient_id,
            "kind": message.kind.value,
            "auth_token": auth_token,
            "body": message.formatted_body,
            "buttons": message.action_buttons,
        }
        self.dispatched.append(record)
        return {"status": "SUCCESS", "channel": "mock", "record": record}


class SlackChannel(BaseChannel):
    """Dispatches to Slack Incoming Webhook with Block Kit formatting."""

    def __init__(self, webhook_url: Optional[str] = None):
        self.webhook_url = webhook_url

    def _dispatch(self, message: ComposedMessage, auth_token: str) -> Dict[str, Any]:
        payload = {
            "text": f"Tally Dispatch: {message.kind.value}",
            "blocks": [
                {
                    "type": "section",
                    "text": {"type": "mrkdwn", "text": message.formatted_body}
                },
                {
                    "type": "actions",
                    "elements": [
                        {
                            "type": "button",
                            "text": {"type": "plain_text", "text": btn.get("label", "Action")},
                            "value": btn.get("action", "click"),
                        }
                        for btn in message.action_buttons
                    ]
                }
            ]
        }

        if self.webhook_url and self.webhook_url.startswith("http"):
            try:
                response = httpx.post(self.webhook_url, json=payload, timeout=5.0)
                response.raise_for_status()
                return {"status": "DELIVERED", "channel": "slack", "http_status": response.status_code}
            except Exception as e:
                return {"status": "FAILED", "channel": "slack", "error": str(e)}

        return {"status": "MOCK_DELIVERED", "channel": "slack", "payload": payload}
